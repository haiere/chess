// Generates js/i18n-data.js from locales/*.json (single source of truth).
// Run: node scripts/gen-i18n.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = {};
for (const l of ['id', 'en']) {
  data[l] = JSON.parse(readFileSync(join(root, 'locales', l + '.json'), 'utf8'));
}
const out = '/* GENERATED by scripts/gen-i18n.mjs from locales/*.json — do not edit by hand. */\n' +
  'export const LOCALES = ' + JSON.stringify(data, null, 2) + ';\n';
writeFileSync(join(root, 'js', 'i18n-data.js'), out, 'utf8');
console.log('wrote js/i18n-data.js');
